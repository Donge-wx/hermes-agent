function mappedDisplayValue(
  value: string | null | undefined,
  mapping: Readonly<Record<string, string>>,
): string {
  const normalized = value?.trim();
  return normalized ? (mapping[normalized.toLocaleLowerCase()] ?? normalized) : "—";
}

